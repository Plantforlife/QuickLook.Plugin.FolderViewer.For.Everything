param(
    [string]$Version
)

$ErrorActionPreference = 'Stop'

if (-not $Version) {
    $Version = $env:FOLDERVIEWER_VERSION
}

if (-not $Version) {
    $Version = (git describe --always --tags --dirty).Trim()
}

$numericMatch = [regex]::Match($Version, '^v?(\d+\.\d+\.\d+(?:\.\d+)?)(?:-|$)')
$assemblyVersion = if ($numericMatch.Success) {
    $parts = @($numericMatch.Groups[1].Value.Split('.') | ForEach-Object { [uint32]$_ })
    if (@($parts | Where-Object { $_ -gt 65534 }).Count -ne 0) {
        throw 'Assembly version components must be between 0 and 65534.'
    }
    while ($parts.Count -lt 4) { $parts += 0 }
    ($parts[0..3] -join '.')
} else {
    '0.0.0.0'
}

$escapedVersion = $Version.Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n')

$text = @"
// This file is generated by update-version.ps1

using System.Reflection;

[assembly: AssemblyVersion("$assemblyVersion")]
[assembly: AssemblyInformationalVersion("$escapedVersion")]
"@

$text | Out-File $PSScriptRoot\..\GitVersion.cs -Encoding utf8

$xml = [xml](Get-Content $PSScriptRoot\..\QuickLook.Plugin.Metadata.Base.config)
$xml.Metadata.Version = $Version
$xml.Save("$PSScriptRoot\..\QuickLook.Plugin.Metadata.config")
